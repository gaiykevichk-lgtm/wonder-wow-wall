# ─── Design Repository ─────────────────────────────────────────────────

class DesignRepository(Protocol):
    async def create(self, design) -> None: ...
    async def get_by_id(self, design_id: str): ...
    async def list_all(self, is_active: bool | None = None, offset: int = 0, limit: int = 100) -> tuple[Sequence, int]: ...
    async def search(self, query: str, limit: int = 20) -> Sequence: ...
    async def update(self, design) -> None: ...
    async def delete(self, design_id: str) -> bool: ...
    async def count(self, category_id: str | None = None, is_active: bool | None = None) -> int: ...
    async def get_by_slug(self, slug: str): ...
    async def list_by_category(self, category_id: str, is_active: bool | None = None) -> Sequence: ...
    async def list_by_ids(self, ids: list[str]) -> Sequence: ...
    async def toggle_visibility(self, design_id: str) -> None: ...
    async def update_preview_image(self, design_id: str, preview_image: str) -> None: ...
    async def list_public_designs(self, category_id: str | None = None, search: str | None = None, sort: str = "name", offset: int = 0, limit: int = 24) -> tuple[Sequence, int]: ...
    async def get_by_id_unchecked(self, design_id: str): ...

